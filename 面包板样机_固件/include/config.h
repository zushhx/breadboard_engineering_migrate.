#define PIN_INA_ALERT    15

// ---------------- 人机 ----------------
#define PIN_LED           2     // IO2 → 1kΩ → LED → GND
#define PIN_BOOT          0

// ---------------- TF 卡（SDMMC 4-bit） ----------------
// 原设计即为此六脚；注意 4-bit 模式必须有 D1/D2/D3，这就是必须买 9P 卡座的原因
#define PIN_SD_CLK       38
