// ---------------- INA226（★ 2026-09-21 决定：不换分流电阻，用模块自带的 0.1Ω） ----------------
// 【原计划为什么要换】模块自带 0.1Ω 时满量程只有 ±0.8192A，当时担心 1A 负载超量程。
// 【最终为什么不换】① 需拆焊 2512 贴片，虚焊与烫坏焊盘的风险高于收益（虚焊的接触电阻
//   比 10mΩ 本身还大，读数会严重偏大且时好时坏）；
//   ② 实际系统峰值约 456mA（WiFi 355 + TF 卡 100 + 传感 1.5），对 819.2mA 有 1.8 倍余量；
//   ③ 0.1Ω 的小电流精度反而更好——失调误差占比与 R 成反比：110mA 时约 0.09%，
//   而 10mΩ 时是 0.91%。代价只是量程变小。
// 【什么时候要改回 10mΩ】若实测电流超过 800mA（例如将来 Qi 那一路同时供设备+充电），
//   或需要覆盖 1A 以上 → 换 10mΩ，并把下面两行改为 0.010f / 8.192f。
//   ★ CAL 不需要跟着动：本驱动令 1 个电流 LSB = 1 个分流电压 LSB（2.5µV），
//     所以 CAL ≡ 0.00512 / 2.5µV = 2048，与 R 无关。
#define INA_ADDR         0x44        // 当前实物两次扫描均为 0x44；之后用 ID 寄存器确认器件
#define SHUNT_OHM        0.100f      // 模块自带值（不拆焊）
#define INA_MAX_CURRENT  0.8192f     // = Vsense 满量程 81.92mV / 0.1Ω
#define INA_CAL          2048        // 仅作文档记录；实际值由 begin() 运行时算出
                                     //   Current_LSB = 0.8192 / 32768 = 25µA
                                     //   0.00512 / (0.000025 × 0.1) = 2048

// ============================================================
//  电量 / 无线充 / 无线 UI —— 2026-09-18 新增
// ============================================================
//
//  ⚠⚠ 引脚为什么只能选 4 和 5（这条不看会白折腾半天）：
//     ESP32-S3 有 ADC1（GPIO1~10）和 ADC2（GPIO11~20）两组。
//     **ADC2 与 WiFi 射频共用硬件，WiFi 一激活 ADC2 就读不出值**
//     （Espressif 官方 FAQ 原文："ADC2 与 Wi-Fi 共用资源，Wi-Fi 激活期间不可读取"）。
//     本方案 UI 必须常开 WiFi → 两路模拟量只能落在 ADC1。
//     ADC1 里：GPIO9/10 被传感器 SPI 占用、GPIO2 是 LED、GPIO3 是 strapping 脚 →
//     实际可用的干净引脚就是 **GPIO4 / GPIO5**。
//
//  分压网络（两路一样）：
//      被测点 ──[10k]──┬──[10k]── GND
//                      └── 100nF ── GND   └── ADC 引脚
//      分压比 = (10k+10k)/10k = 2.0，节点源阻抗 10k∥10k = 5kΩ（S3 可接受）
//      电池 4.20V → 2.10V，Qi 输出 5.25V → 2.63V，都在 ADC 量程内
#define PIN_VBAT         4     // ADC1_CH3：电池正极经 10k/10k
#define PIN_QIDET        5     // ADC1_CH4：Qi 接收模块 5V 输出（★ 取在 SS34 之前）

#define ADC_DIV_RATIO    2.0f  // 分压比 (R上+R下)/R下
#define ADC_ATTEN        ADC_11db
// 实测校准系数：拿万用表量出真实电压，除以固件读到的值，填进来（1.0 = 不校准）
// ESP32 ADC 有 ±5% 级非线性，做电量指示够用；要精确就得逐个板标定。
#define ADC_TRIM_VBAT    1.0f
#define ADC_TRIM_QI      1.0f
#define ADC_AVG_N        16    // 每次读数取 16 次平均

// 电池电量判定门限（单节锂电，开路电压法）
// ⚠ 诚实边界：电压法在锂电平台期（3.7~3.9V）误差可达 ±15%，
//   且带负载时会读到偏低的电压。这里只在电流较小时更新 SOC，并做缓变处理。
#define VBAT_EMPTY       3.30f   // 低于此判 0%
#define VBAT_FULL        4.15f   // 高于此判 100%
#define CHG_DET_V        4.30f   // Qi 输出 > 4.30V 视为"在场"（带 0.4V 迟滞）
#define CHG_LOST_V       3.90f   // 低于此视为"已移开"
#define USB_DET_V        4.40f   // 5V 轨电压 > 此值视为有外部 5V

// ============================================================
//  无线 UI（WiFi AP + HTTP + WebSocket）
// ============================================================
#define NET_SSID_PREFIX  "VibMon-"    // 实际 SSID = VibMon-XXXX（XXXX 取 MAC 后两字节）
#define NET_PASS         "vibmon2026" // ≥8 位；WPA2
#define NET_CHANNEL      6
#define NET_HTTP_PORT    80           // HTTP 与 WebSocket 共用 80（路径 /ws）
#define NET_MAX_CLIENTS  4
// ★ 发射功率压到 11dBm（默认约 19.5dBm）：
//   板载 ME6217 LDO 热限流约 588mA，WiFi 满功率峰值 355mA + TF 卡写入 ~100mA
//   已接近上限 → 降功率换余量。实测 11dBm 在 10m 内足够。
#define NET_TX_POWER     WIFI_POWER_11dBm

// ============================================================
//  显示抽帧参数（"被处理过的、不大的实时信号"）
// ============================================================
//  原始 26.667kHz 不能直接上网：160 KB/s 会同时压垮 WiFi 与 UI。
//  做法 = 示波器式 min/max 包络抽帧：每 DISP_DECIM 个原始样本压成 1 个
//  抽帧点，该点同时记住这 26 个样本里的最小值和最大值。
//  ★ 为什么不直接隔点抽样：冲击/敲击类振动是窄脉冲，隔点抽样会整段抽没，
//    而 min/max 包络**峰值信息一个都不丢**（显示上等价于峰值检波）。
//  带宽账：26667 / 26 = 1025.6 Hz → 32 点/帧 → 32.05 fps
//          每帧 32×3轴×2值×2B + 14B 头 ≈ 398 B → 12.7 KB/s（可忽略）
#define DISP_DECIM       26       // 抽帧比 → 抽帧后约 1026 Hz
#define DISP_PTS         32       // 每帧抽帧点数
#define DISP_QUEUE       8        // 帧队列深度（8×396B ≈ 3.2KB DRAM）
#define DISP_AXES        3
// 直流估计（一阶低通）时间常数，秒。用它估出重力/零点，再从信号里减掉，
// 这样"静置时 Z 轴显示 0 g"而不是 1 g —— 振动监测看的是交流分量。
#define DISP_DC_TAU_S    3.0f
// RMS / 峰值 的上报平滑：状态帧每 500ms 一次
#define STATUS_PERIOD_MS 500

// ---------------- 采集参数 ----------------
// IIS3DWB 满速 ODR = 26.667 kHz（AN5444：CTRL1_XL = 0xA0，FS = ±2g）
#define SAMPLE_RATE_HZ   26667
#define RECORD_SECONDS   90
#define BUF_SAMPLES      2048        // 批写缓冲样本数（2048 × 6B = 12KB）
#define MAX_SEGMENT_SEC  10          // 分段落盘：掉电最多丢当前这一段

// ============================================================
//  录制保真优先：录制期间关掉 WiFi
// ============================================================
//  为什么值得做成一个开关：
//   功耗账（ESP32-S3-WROOM-1 手册 Table12/13/14 实测值）——
//     电台关（Modem-sleep @240MHz）  ≈ 33~108 mA
//     电台保持关联（RX 95mA 为主）    ≈ +100 mA
//     TX 峰值（11b 1Mbps @20.5dBm）  = 355 mA（瞬时）
//   ★ 关键认知：**耗电大头是"电台开着"，不是"传了多少数据"**。
//     我们的显示流只有 12.7 KB/s，在 54Mbps 下只占空口 0.5%
//     （最坏被压到 11b 1Mbps 也才 16%），平均只多花 2~10 mA。
//     → 所以"把帧率从 32fps 降到 8fps"省不下电（电台照样开），不值得做；
//       要省只能整个把电台关掉。
//
//  关掉电台换来两件事：
//    ① 去掉射频对 26.667kHz 采集的干扰（WiFi 中断会抢 core 0，
//       而写卡任务也被钉在 core 0 → 后果是"写卡丢样本"）
//    ② 去掉 TX 355mA 峰值电流对板载 LDO 的压力（ME6217 热限流约 588mA）
//
//  代价：录制期间浏览器 UI 断线，录完自动恢复并重连（UI 会提示"静默录制中"）。
//
//  ★ 定位（2026-09-18 用户拍板）：**这是排障手段，不是常规工况。**
//    本版的正常用法就是「实时显示 + 写 SD 卡同时进行」—— 固件本来就是这么设计的，
//    两条链路物理分开（core1 采集 → PSRAM 环形缓冲 → core0 写卡；core1 抽帧 → core0 推流），
//    **不存在"要实时就不能写卡"这种取舍。**
//    只有「写入丢帧」持续不为 0 时才需要打开它，用来定位是射频/电流干扰还是别的。
//  ⚠ 与"连续推流看波形"互斥 —— 打开即进入另一种工况，所以默认关闭。
#define REC_WIFI_OFF_DEFAULT   0     // 0 = 正常工况：录制时保持 WiFi，实时与写卡同时跑
#define REC_WIFI_OFF_DELAY_MS  500   // 先把手上的 ack / 状态帧发出去，再关电台

// ---------------- 传感器标度 ----------------
// ✅ 已核实：DS12569 Rev8 Table 3「Mechanical characteristics」
//    工厂校准修调后的值，公差 ±2%（@Vdd = 3.0 V, T = 25 °C）
//      @FS = ±2 g  → 0.061 mg/LSB
//      @FS = ±4 g  → 0.122
//      @FS = ±8 g  → 0.244
//      @FS = ±16 g → 0.488
// 静置正反重力方向读数用于分离零偏和标度；单姿态偏离 1g 不能直接判灵敏度。
#define SENS_MG_PER_LSB  0.061f
